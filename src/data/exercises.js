export function getExerciseById(id) {
  return exercises.find(e => e.id === id);
}

export function getExercisesByMuscle(muscle) {
  return exercises.filter(e => e.muscle === muscle);
}

export function getExercisesByEquipment(equipment) {
  return exercises.filter(e => e.equipment === equipment);
}

export function formatReps(exercise) {
  if (exercise.repsType === 'time') return `${exercise.reps} сек`;
  if (exercise.repsType === 'minutes') return `${exercise.reps} мин`;
  return `${exercise.reps} повт`;
}

export function formatSetsReps(exercise) {
  return `${exercise.sets} × ${formatReps(exercise)}`;
}
